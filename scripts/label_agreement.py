"""Agreement between the first labeller and a human checker.

Reads the answers file that the checker downloaded from the sheet of
scripts.label_check_kit, the key that was kept apart, and the first
labels. Reports, for three labels (S, B, F) and for "S against the rest"
(the comparison the paper uses):

    raw agreement and Cohen's kappa, each with a bootstrap interval over
    the moments; the table of first label against checker label;
    the share of S at speech onsets and at random seconds with the
    checker's labels, next to the same shares with the first labels.

With 60 moments the last comparison is only a direction, not a test.

With two or more checkers (give several files) it also reports the
agreement between the checkers.

Usage:
    python -m scripts.label_agreement --dataset egoextra --answers a.json [b.json ...]
Outputs: reports/<dataset>_label_agreement.json and .md
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd


def kappa(a: np.ndarray, b: np.ndarray) -> float:
    po = float((a == b).mean())
    pe = float(sum((a == v).mean() * (b == v).mean() for v in np.union1d(a, b)))
    return float("nan") if pe >= 1 else (po - pe) / (1 - pe)


def with_interval(fn, a, b, rng, n=5000):
    idx = rng.integers(0, len(a), (n, len(a)))
    vals = np.array([fn(a[i], b[i]) for i in idx])
    lo, hi = np.nanpercentile(vals, [2.5, 97.5])
    return {"value": round(float(fn(a, b)), 3), "lo": round(float(lo), 3), "hi": round(float(hi), 3)}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dataset", required=True)
    ap.add_argument("--answers", required=True, nargs="+", help="one file per checker")
    ap.add_argument("--key", default=None)
    a = ap.parse_args()
    key = json.loads(Path(a.key or f"runs/label_check/{a.dataset}_check_key.json").read_text())
    lab = pd.read_csv(f"reports/{a.dataset}_hand_labels.csv", dtype={"recording": str}).set_index("id")
    ids = [key[n] for n in key]
    cols = {"first labels": lab.loc[ids, "label"].to_numpy()}
    for j, f in enumerate(a.answers):
        ans = json.loads(Path(f).read_text(encoding="utf-8"))
        missing = [n for n in key if n not in ans["answers"]]
        if missing:
            raise SystemExit(f"{f}: {len(missing)} moments have no answer: {missing[:10]}")
        cols[f"checker {j + 1}"] = np.array([ans["answers"][n] for n in key])
    names = list(cols)
    rng = np.random.default_rng(0)
    agree = lambda x, y: float((x == y).mean())
    res = {"dataset": a.dataset, "n": len(ids), "pairs": [], "share_S": {}}
    for i in range(len(names)):
        for j in range(i + 1, len(names)):
            f, s = cols[names[i]], cols[names[j]]
            res["pairs"].append({
                "a": names[i], "b": names[j],
                "three_labels": {"agreement": with_interval(agree, f, s, rng), "kappa": with_interval(kappa, f, s, rng)},
                "S_against_rest": {"agreement": with_interval(agree, f == "S", s == "S", rng),
                                   "kappa": with_interval(kappa, f == "S", s == "S", rng)},
                "table": pd.crosstab(pd.Series(f), pd.Series(s)).reindex(
                    index=list("SBF"), columns=list("SBF"), fill_value=0).to_dict("index")})
    group = np.where(lab.loc[ids, "kind"].to_numpy() == "random", "random seconds", "speech onsets")
    for g in ("speech onsets", "random seconds"):
        res["share_S"][g] = {"n": int((group == g).sum()),
                             **{k: round(float((v[group == g] == "S").mean()), 3) for k, v in cols.items()}}
    Path(f"reports/{a.dataset}_label_agreement.json").write_text(json.dumps(res, indent=1))

    fmt = lambda v: f"{v['value']:.2f} ({v['lo']:.2f} to {v['hi']:.2f})"
    L = [f"# {a.dataset}: agreement of human checkers with the first labels", "",
         f"Generated by `python -m scripts.label_agreement`. {res['n']} moments, drawn at random by "
         f"`scripts.label_check_kit`, the same number of each kind. A checker did not see the first label, "
         f"the kind of the moment or the labels of another checker. Intervals: 95%, 5,000 resamples of the "
         f"moments. The agreement between two checkers shows how far two people agree on this task; the "
         f"agreement with the first labels should be read against it.", "",
         "| pair | labels | agreement | Cohen's kappa |", "|---|---|---|---|"]
    for p in res["pairs"]:
        L += [f"| {p['a']} / {p['b']} | S, B, F | {fmt(p['three_labels']['agreement'])} | {fmt(p['three_labels']['kappa'])} |",
              f"| {p['a']} / {p['b']} | S against the rest | {fmt(p['S_against_rest']['agreement'])} | {fmt(p['S_against_rest']['kappa'])} |"]
    for p in res["pairs"]:
        L += ["", f"{p['a']} (rows) against {p['b']} (columns):", "", "| | S | B | F |", "|---|---|---|---|"]
        L += [f"| {r} | " + " | ".join(str(p["table"][r][c]) for c in "SBF") + " |" for r in "SBF"]
    L += ["", "Share of S (with 60 moments this shows a direction only):", "",
          "| moments | n | " + " | ".join(names) + " |", "|---|---|" + "---|" * len(names)]
    L += [f"| {g} | {v['n']} | " + " | ".join(f"{v[k]:.0%}" for k in names) + " |" for g, v in res["share_S"].items()]
    Path(f"reports/{a.dataset}_label_agreement.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()

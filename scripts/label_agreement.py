"""Agreement between the first labeller and a human checker.

Reads the answers file that the checker downloaded from the sheet of
scripts.label_check_kit, the key that was kept apart, and the first
labels. Reports, for three labels (S, B, F) and for "S against the rest"
(the comparison the paper uses):

    raw agreement and Cohen's kappa, each with a bootstrap interval over
    the moments; the table of first label against checker label;
    the share of S at speech onsets and at random seconds with the
    checker's labels, next to the same shares with the first labels.

With 60 moments the last comparison is only a direction, not a test.

Usage:
    python -m scripts.label_agreement --dataset egoextra --answers path/to/egoextra_check_answers.json
Outputs: reports/<dataset>_label_agreement.json and .md
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd


def kappa(a: np.ndarray, b: np.ndarray) -> float:
    po = float((a == b).mean())
    pe = float(sum((a == v).mean() * (b == v).mean() for v in np.union1d(a, b)))
    return float("nan") if pe >= 1 else (po - pe) / (1 - pe)


def with_interval(fn, a, b, rng, n=5000):
    idx = rng.integers(0, len(a), (n, len(a)))
    vals = np.array([fn(a[i], b[i]) for i in idx])
    lo, hi = np.nanpercentile(vals, [2.5, 97.5])
    return {"value": round(float(fn(a, b)), 3), "lo": round(float(lo), 3), "hi": round(float(hi), 3)}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dataset", required=True)
    ap.add_argument("--answers", required=True)
    ap.add_argument("--key", default=None)
    a = ap.parse_args()
    ans = json.loads(Path(a.answers).read_text(encoding="utf-8"))
    key = json.loads(Path(a.key or f"runs/label_check/{a.dataset}_check_key.json").read_text())
    lab = pd.read_csv(f"reports/{a.dataset}_hand_labels.csv", dtype={"recording": str}).set_index("id")
    missing = [n for n in key if n not in ans["answers"]]
    if missing:
        raise SystemExit(f"{len(missing)} moments have no answer: {missing[:10]}")
    d = pd.DataFrame({"id": [key[n] for n in key], "second": [ans["answers"][n] for n in key]})
    d["first"] = lab.loc[d.id, "label"].to_numpy()
    d["kind"] = lab.loc[d.id, "kind"].to_numpy()
    rng = np.random.default_rng(0)
    f, s = d["first"].to_numpy(), d["second"].to_numpy()
    agree = lambda x, y: float((x == y).mean())
    res = {"dataset": a.dataset, "n": int(len(d)), "checker": ans.get("who", ""),
           "three_labels": {"agreement": with_interval(agree, f, s, rng), "kappa": with_interval(kappa, f, s, rng)},
           "S_against_rest": {"agreement": with_interval(agree, f == "S", s == "S", rng),
                              "kappa": with_interval(kappa, f == "S", s == "S", rng)},
           "table": pd.crosstab(d["first"], d["second"]).reindex(index=list("SBF"), columns=list("SBF"),
                                                                 fill_value=0).to_dict("index"),
           "share_S": {}}
    d["group"] = np.where(d.kind == "random", "random seconds", "speech onsets")
    for g, sub in d.groupby("group"):
        res["share_S"][g] = {"n": int(len(sub)), "first": round(float((sub["first"] == "S").mean()), 3),
                             "second": round(float((sub["second"] == "S").mean()), 3)}
    Path(f"reports/{a.dataset}_label_agreement.json").write_text(json.dumps(res, indent=1))

    fmt = lambda v: f"{v['value']:.2f} ({v['lo']:.2f} to {v['hi']:.2f})"
    L = [f"# {a.dataset}: agreement of a human checker with the first labels", "",
         f"Generated by `python -m scripts.label_agreement`. {res['n']} moments, drawn at random by "
         f"`scripts.label_check_kit`, the same number of each kind. The checker did not see the first label "
         f"or the kind of the moment. Intervals: 95%, 5,000 resamples of the moments.", "",
         "| labels | agreement | Cohen's kappa |", "|---|---|---|",
         f"| S, B, F | {fmt(res['three_labels']['agreement'])} | {fmt(res['three_labels']['kappa'])} |",
         f"| S against the rest | {fmt(res['S_against_rest']['agreement'])} | {fmt(res['S_against_rest']['kappa'])} |",
         "", "First label (rows) against checker label (columns):", "", "| | S | B | F |", "|---|---|---|---|"]
    L += [f"| {r} | " + " | ".join(str(res["table"][r][c]) for c in "SBF") + " |" for r in "SBF"]
    L += ["", "Share of S (with 60 moments this shows a direction only):", "",
          "| moments | n | first labels | checker |", "|---|---|---|---|"]
    L += [f"| {g} | {v['n']} | {v['first']:.0%} | {v['second']:.0%} |" for g, v in res["share_S"].items()]
    Path(f"reports/{a.dataset}_label_agreement.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()

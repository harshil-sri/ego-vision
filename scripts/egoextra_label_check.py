"""Ego-EXTRA: a labelled sample of the two assembly-like scenarios.

The avoidance of screw, unscrew and insert actions by speech was found on
HoloAssist with human labels and not on WTaG (cooking), where such
actions are rare. Ego-EXTRA's bike workshop (01) and furniture assembly
(03) have many of them, but no labels, and the head trained on HoloAssist
is weak outside it (scripts.wtag_label_check). So 420 moments were
labelled by eye, in two batches.

First batch (ids 1 to 240, 2026-11-12):

    80 onsets of a trainee turn
    80 onsets of an unasked, long expert turn (scripts.egoextra_speech)
    80 random seconds in the same videos (same mix of videos)
    drawn at random from scenarios 01 and 03, shuffled, labelled blind.
    Each moment: 4 frames of the 2 s that end at the moment, central
    500 x 500 of the 704 x 704 view.

Second batch (ids 241 to 420, 2026-11-13): furniture assembly only, 60 of
each kind, same protocol, no moment within 3 s of a first-batch onset.

    S  screw, unscrew or insert in progress (screwdriver or hex key
       turning, a screw or dowel going into its hole, a cap being turned)
    B  other precise work in progress (hammering, fitting a tyre or tube,
       wiping, aligning two parts, pumping, pliers)
    F  everything else (hold, carry, reach, pick, look, gesture, no hands)

Labeller: the AI assistant that wrote this project's code. One pass, no
second rater. Labels in reports/egoextra_hand_labels.csv.

Output: share of S and of S or B at each kind of onset and at random
seconds, and the ratio with a bootstrap interval (the two samples are
resampled apart). No model is used.

Usage:  python -m scripts.egoextra_label_check
Outputs: reports/egoextra_label_check.json, reports/egoextra_label_check.md
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

KINDS = (("expert_unasked", "expert: unasked long turn"), ("trainee_turn", "trainee: turn"),
         ("speech", "either (both pooled)"))
SCEN = {"01": "bike workshop", "03": "furniture assembly"}


def main() -> None:
    rng = np.random.default_rng(0)
    lab = pd.read_csv("reports/egoextra_hand_labels.csv", dtype={"recording": str})
    lab["scenario"] = lab.recording.str[:2]
    res = {"items": int(len(lab)), "sets": {}}

    def table(d):
        rd = d[d.kind == "random"]
        out = {"counts": {k: {l: int((d[d.kind == k].label == l).sum()) for l in "SBF"}
                          for k in ("expert_unasked", "trainee_turn", "random")}, "ratio": {}}
        for kind, kname in KINDS:
            on = d[d.kind != "random"] if kind == "speech" else d[d.kind == kind]
            for name, cls in (("S (screw, unscrew, insert)", "S"), ("S or B (any precise work)", "SB")):
                a, b = on.label.isin(list(cls)).to_numpy(), rd.label.isin(list(cls)).to_numpy()
                i = rng.integers(0, len(a), size=(5000, len(a)))
                j = rng.integers(0, len(b), size=(5000, len(b)))
                r = a[i].mean(1) / np.maximum(b[j].mean(1), 1e-9)
                out["ratio"][f"{kname} | {name}"] = {
                    "n": int(len(a)), "onset": round(float(a.mean()), 3), "random": round(float(b.mean()), 3),
                    "ratio": round(float(a.mean() / max(b.mean(), 1e-9)), 2),
                    "ci95": [round(float(np.percentile(r, 2.5)), 2), round(float(np.percentile(r, 97.5)), 2)]}
        return out

    res["sets"]["both scenarios"] = table(lab)
    for s, n in SCEN.items():
        res["sets"][n] = table(lab[lab.scenario == s])
    f = lab[lab.scenario == "03"]
    res["sets"]["furniture assembly, first batch (ids 1 to 240)"] = table(f[f.id <= 240])
    res["sets"]["furniture assembly, second batch (ids 241 to 420)"] = table(f[f.id > 240])
    Path("reports/egoextra_label_check.json").write_text(json.dumps(res, indent=2))

    L = [f"# Ego-EXTRA: {len(lab)} moments labelled by eye (bike workshop, furniture assembly)", "",
         "Generated by `python -m scripts.egoextra_label_check` from `reports/egoextra_hand_labels.csv`. "
         "Labels by the AI assistant, blind to onset or random, one pass, no second rater. "
         "No model is used. See the script docstring for the protocol.", ""]
    for sname, t in res["sets"].items():
        c = t["counts"]
        L += [f"## {sname}", "", "| moments | n | S | B | F |", "|---|---|---|---|---|"]
        for k in c:
            L.append(f"| {k} | {sum(c[k].values())} | {c[k]['S']} | {c[k]['B']} | {c[k]['F']} |")
        L += ["", "| onsets | hands | n | share at onsets | share at random seconds | ratio | 95% interval |",
              "|---|---|---|---|---|---|---|"]
        for name, r in t["ratio"].items():
            who, hands = name.split(" | ")
            few = r["random"] * sum(c["random"].values()) < 5            # under 5 such random seconds: no ratio
            L.append(f"| {who} | {hands} | {r['n']} | {r['onset']:.0%} | {r['random']:.0%} | "
                     + ("too few | too few |" if few else
                        f"{r['ratio']:.2f} | {r['ci95'][0]:.2f} to {r['ci95'][1]:.2f} |"))
        L.append("")
    Path("reports/egoextra_label_check.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()

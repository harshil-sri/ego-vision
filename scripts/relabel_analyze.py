"""Analysis of the human relabelling (scripts.relabel_build, study/label/).

Written before any human label was collected. The plan is in
study/label/ANALYSIS_PLAN.md.

Input: runs/label_check/relabel/answers/, any mix of
    *.json   one result per file (the "Download my labels" button)
    *.txt    result codes, one per line ("Copy as text": base64 of the JSON)
    *.csv    the "labels" tab of the collection sheet (column "json")
plus the keys in runs/label_check/relabel/keys/ (batch number -> id).

Rules (fixed in advance):
    - A result counts only if every moment of its batch has a label.
    - The same run sent twice: the later one is kept (a labeller may go
      back and change an answer).
    - Per batch, the first two complete results from two DIFFERENT people
      (different name and different browser id), by finishing time, are
      labeller h1 and h2. Further results are reported for agreement only.
    - Agreed label: h1 and h2 chose the same label; otherwise empty.

Outputs:
    reports/{egoextra,wtag}_hand_labels_human.csv   ids, the AI label, h1, h2, agreed (no names)
    reports/relabel_human.json, reports/relabel_human.md
    runs/label_check/relabel/acknowledgements.txt    names of those who opted in (private)

Usage:  python -m scripts.relabel_analyze
"""

from __future__ import annotations

import argparse
import base64
import json
from pathlib import Path

import numpy as np
import pandas as pd

from scripts.label_agreement import kappa

ONSETS = {"egoextra": [("expert_unasked", "expert, unasked long turn"), ("trainee_turn", "trainee, turn")],
          "wtag": [("onset", "instructor, routine instruction"), ("user_question", "user, question")]}
SETS = ["ai", "h1", "h2", "agreed"]
CLASSES = [("S", "S (screw, unscrew, insert)"), ("SB", "S or B (any precise work)")]


def read_results(folder: Path) -> list[dict]:
    texts = []
    for p in sorted(folder.glob("*")):
        if p.suffix == ".json":
            texts.append(p.read_text(encoding="utf-8"))
        elif p.suffix == ".txt":
            for line in p.read_text(encoding="utf-8").split():
                try:
                    texts.append(base64.b64decode(line.strip()).decode("utf-8"))
                except Exception:
                    print(f"  skipped a line in {p.name}: not a result code")
        elif p.suffix == ".csv":
            texts += pd.read_csv(p)["json"].dropna().astype(str).tolist()
    out = {}
    for t in texts:
        try:
            r = json.loads(t)
        except json.JSONDecodeError:
            continue
        if r.get("kind") != "labels":
            continue
        if r["run"] not in out or r.get("t1", "") > out[r["run"]].get("t1", ""):
            out[r["run"]] = r
    return list(out.values())


def ratio(on: np.ndarray, rd: np.ndarray, rng, n=5000) -> dict:
    i = rng.integers(0, len(on), size=(n, len(on)))
    j = rng.integers(0, len(rd), size=(n, len(rd)))
    r = on[i].mean(1) / np.maximum(rd[j].mean(1), 1e-9)
    few = rd.sum() < 5
    return {"n_onsets": int(len(on)), "n_random": int(len(rd)), "onset": round(float(on.mean()), 3),
            "random": round(float(rd.mean()), 3),
            "ratio": None if few else round(float(on.mean() / max(rd.mean(), 1e-9)), 2),
            "ci95": None if few else [round(float(np.percentile(r, 2.5)), 2), round(float(np.percentile(r, 97.5)), 2)]}


def kappa_ci(a: np.ndarray, b: np.ndarray, rng, n=5000) -> dict:
    idx = rng.integers(0, len(a), (n, len(a)))
    vals = np.array([kappa(a[i], b[i]) for i in idx])
    lo, hi = np.nanpercentile(vals, [2.5, 97.5])
    return {"n": int(len(a)), "agreement": round(float((a == b).mean()), 3), "kappa": round(kappa(a, b), 3),
            "ci95": [round(float(lo), 3), round(float(hi), 3)]}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--answers", default="runs/label_check/relabel/answers")
    ap.add_argument("--keys", default="runs/label_check/relabel/keys")
    a = ap.parse_args()
    rng = np.random.default_rng(0)
    results = read_results(Path(a.answers))
    keys = {p.stem: json.loads(p.read_text()) for p in Path(a.keys).glob("*.json")}
    res, acks, L = {"datasets": {}}, set(), ["# Human relabelling: agreement and the onset analysis", "",
                                             "Generated by `python -m scripts.relabel_analyze`. Plan: `study/label/ANALYSIS_PLAN.md`.", ""]
    codes: dict[str, str] = {}
    for ds in ("egoextra", "wtag"):
        lab = pd.read_csv(f"reports/{ds}_hand_labels.csv", dtype={"recording": str}).rename(columns={"label": "ai"})
        lab["h1"], lab["h2"] = "", ""
        extra, per_batch = [], {}
        for name in sorted(k for k in keys if k.startswith(ds + "-")):
            b, key = int(name.split("-")[1]), keys[name]
            done = []
            for r in results:
                if r["ds"] != ds or r["batch"] != b:
                    continue
                ans = {str(x["n"]): x.get("l") for x in r["answers"]}
                if all(ans.get(n) in ("S", "B", "F") for n in key):
                    done.append((r.get("t1", ""), r, ans))
            done.sort(key=lambda x: x[0])
            chosen, who = [], set()
            for t1, r, ans in done:
                person = (r.get("name", "").strip().lower(), r.get("labeller"))
                if any(person[0] == w[0] or person[1] == w[1] for w in who):
                    continue
                who.add(person)
                code = codes.setdefault(r.get("labeller", "") + "|" + person[0], f"L{len(codes) + 1:02d}")
                (chosen if len(chosen) < 2 else extra).append((code, r, ans))
                if r.get("ack") and r.get("name"):
                    acks.add(r["name"].strip())
            per_batch[name] = [c[0] for c in chosen]
            for slot, (code, r, ans) in zip(("h1", "h2"), chosen):
                ids = {int(key[n]): ans[n] for n in key}
                m = lab.id.isin(ids)
                lab.loc[m, slot] = lab.loc[m, "id"].map(ids)
        lab["agreed"] = np.where((lab.h1 != "") & (lab.h1 == lab.h2), lab.h1, "")
        lab[["id", "recording", "t_s", "kind", "ai", "h1", "h2", "agreed"]].to_csv(
            f"reports/{ds}_hand_labels_human.csv", index=False)

        both = lab[(lab.h1 != "") & (lab.h2 != "")]
        agree = {}
        for x, y in (("h1", "h2"), ("ai", "h1"), ("ai", "h2")):
            for cname, f in (("S, B, F", lambda s: s), ("S vs not S", lambda s: (s == "S").astype(str)),
                             ("S or B vs F", lambda s: s.isin(["S", "B"]).astype(str))):
                d = lab[(lab[x] != "") & (lab[y] != "")]
                if len(d):
                    agree[f"{x} vs {y} | {cname}"] = kappa_ci(f(d[x]).to_numpy(), f(d[y]).to_numpy(), rng)
        subsets = {"all": lab}
        if ds == "egoextra":
            subsets["furniture assembly"] = lab[lab.recording.str[:2] == "03"]
        ratios = {}
        for sname, d in subsets.items():
            for s in SETS:
                dd = d[d[s] != ""]
                rd = dd[dd.kind == "random"]
                for kind, kname in ONSETS[ds] + [("speech", "either (both pooled)")]:
                    on = dd[dd.kind != "random"] if kind == "speech" else dd[dd.kind == kind]
                    for cls, cname in CLASSES:
                        if len(on) and len(rd):
                            ratios[f"{sname} | {s} | {kname} | {cname}"] = ratio(
                                on[s].isin(list(cls)).to_numpy(), rd[s].isin(list(cls)).to_numpy(), rng)
        res["datasets"][ds] = {"moments": int(len(lab)), "with_two_humans": int(len(both)),
                               "agreed": int((lab.agreed != "").sum()), "batches": per_batch,
                               "extra_results": len(extra), "agreement": agree, "ratios": ratios}

        L += [f"## {ds}", "", f"{len(lab)} moments; {len(both)} labelled by two people; "
              f"{int((lab.agreed != '').sum())} with the same label from both.", "",
              "| labels | classes | n | agreement | Cohen's kappa (95% interval) |", "|---|---|---|---|---|"]
        for k, v in agree.items():
            pair, cname = k.split(" | ")
            L.append(f"| {pair} | {cname} | {v['n']} | {v['agreement']:.0%} | {v['kappa']:.2f} "
                     f"({v['ci95'][0]:.2f} to {v['ci95'][1]:.2f}) |")
        L += ["", "| subset | labels | onsets | hands | n | at onsets | at random seconds | ratio (95% interval) |",
              "|---|---|---|---|---|---|---|---|"]
        for k, v in ratios.items():
            sname, s, kname, cname = k.split(" | ")
            r = "too few random seconds" if v["ratio"] is None else f"{v['ratio']:.2f} ({v['ci95'][0]:.2f} to {v['ci95'][1]:.2f})"
            L.append(f"| {sname} | {s} | {kname} | {cname} | {v['n_onsets']} | {v['onset']:.0%} | {v['random']:.0%} | {r} |")
        L.append("")
    Path("reports/relabel_human.json").write_text(json.dumps(res, indent=2), encoding="utf-8")
    Path("reports/relabel_human.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    Path("runs/label_check/relabel/acknowledgements.txt").write_text("\n".join(sorted(acks)) + "\n", encoding="utf-8")
    print("\n".join(L[:40]))
    print(f"... {len(results)} results read; {len(acks)} names for the acknowledgements (private file)")


if __name__ == "__main__":
    main()

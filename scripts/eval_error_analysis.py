"""Per-verb error analysis of the banked val predictions (item-5 triage).

Answers, from the cached smoother-eval predictions only (CPU, seconds):

  1. Which verbs can the checkpoint actually do? Per-verb precision /
     recall / F1 at segment-level argmax, with support counts.
  2. Where does it lose mass? Top confusion pairs (true -> pred).
  3. Is the recommended smoother config sensitive to min_conf?
     Sweep 0.3-0.7 for the majority smoother, same replay protocol as
     the bake-off (reuses _score from scripts.eval_smoothers).

The point: if errors concentrate in a few verb pairs, a regularized
retrain (item 5) has a target; if they are diffuse, retraining the same
single-frame variant will not move the demo and the money is better
spent on the reasoning layer (already measured) or a stronger variant.

Usage:
    python3 -m scripts.eval_error_analysis            # uses/creates the cache
"""

from __future__ import annotations

import argparse
from collections import Counter
from pathlib import Path

import numpy as np


def _per_verb_rows(verb, probs, verbs):
    """Precision/recall/F1 + support at argmax (raw, no smoother)."""
    idx = {v: i for i, v in enumerate(verbs)}
    pred = [verbs[int(np.argmax(p))] for p in probs]
    tp, fp, fn = Counter(), Counter(), Counter()
    for t, p in zip(verb, pred):
        if t == p:
            tp[t] += 1
        else:
            fp[p] += 1
            fn[t] += 1
    rows = []
    for v in verbs:
        prec = tp[v] / (tp[v] + fp[v]) if tp[v] + fp[v] else None
        rec = tp[v] / (tp[v] + fn[v]) if tp[v] + fn[v] else None
        f1 = (2 * prec * rec / (prec + rec)) if prec and rec else None
        rows.append((v, tp[v] + fn[v], prec, rec, f1))
    return rows, pred


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--cache", default="runs/eval_cache/val_preds.npz")
    ap.add_argument("--out", default="reports/val_error_analysis.md")
    ap.add_argument("--run-dir", default="runs/baseline",
                    help="only used if the cache must be (re)built")
    ap.add_argument("--recipe", default="recipes/example_salad.yaml",
                    help="demo recipe whose verb set defines 'in-recipe' "
                         "segments (the recipe prior masks the rest at "
                         "runtime, so their errors mostly don't reach the "
                         "state machine)")
    args = ap.parse_args()

    cache = Path(args.cache)
    if not cache.exists():
        from scripts.eval_smoothers import _build_cache, _load_val_segments
        print("cache missing — building (one-off, ~90 s)...")
        _build_cache(Path(args.run_dir), _load_val_segments(Path(args.run_dir)),
                     cache)
    z = np.load(cache, allow_pickle=True)
    video, verb, probs = z["video"], z["verb"], z["probs"]
    verbs = [str(v) for v in z["verbs"]]

    # ---- 1. per-verb metrics at argmax --------------------------------
    rows, pred = _per_verb_rows(verb, probs, verbs)
    n = len(verb)
    acc = sum(t == p for t, p in zip(verb, pred)) / n

    # ---- 2. confusion pairs -------------------------------------------
    conf = Counter((str(t), p) for t, p in zip(verb, pred) if t != p)
    total_err = sum(conf.values())

    # demo subset: segments whose TRUE verb is legal in the recipe —
    # these are the errors the prior cannot mask away
    import yaml
    recipe = yaml.safe_load(Path(args.recipe).read_text())
    recipe_verbs = sorted({s["verb"] for s in recipe["steps"]})
    mask = np.array([str(t) in recipe_verbs for t in verb])
    demo_acc = (np.array([t == p for t, p in zip(verb, pred)])[mask]).mean()

    # ---- 3. min_conf sweep (majority smoother, bake-off protocol) ------
    from scripts.eval_smoothers import _score
    from src.pipeline.smoothers import make_smoother
    by_video: dict[str, list] = {}
    for v, lb, p in zip(video, verb, probs):
        by_video.setdefault(str(v), []).append((p, str(lb)))
    series = [(np.stack([x[0] for x in r]), [x[1] for x in r])
              for r in by_video.values()]
    sweep = []
    for mc in (0.3, 0.4, 0.5, 0.6, 0.7):
        sweep.append(_score(f"majority@{mc}", series, verbs,
                            lambda: make_smoother("majority", verbs, k=5,
                                                  min_conf=mc), mc))

    # ---- report --------------------------------------------------------
    lines = [
        "# Val error analysis — runs/baseline (ep 1, val_mca 0.2205)", "",
        f"Source: `{cache}` ({n} segments, {len(by_video)} videos), "
        "segment-level argmax, no smoother. Generated by "
        "`python3 -m scripts.eval_error_analysis`.", "",
        f"Overall segment accuracy: **{acc:.4f}** "
        f"({sum(t == p for t, p in zip(verb, pred))}/{n}); "
        f"majority-class baseline: 0.189.", "",
        "## 1. Per-verb precision / recall (argmax)", "",
        "| verb | support | precision | recall | F1 |",
        "|---|---|---|---|---|",
    ]
    for v, sup, prec, rec, f1 in rows:
        fmt = lambda x: "—" if x is None else f"{x:.3f}"  # noqa: E731
        lines.append(f"| {v} | {sup} | {fmt(prec)} | {fmt(rec)} | {fmt(f1)} |")

    lines += ["", "## 2. Top confusion pairs (true -> predicted)", "",
              f"{total_err} misclassified segments; the top pairs below "
              "carry the indicated share.", "",
              "| true | predicted | count | % of errors |", "|---|---|---|---|"]
    for (t, p), c in conf.most_common(10):
        lines.append(f"| {t} | {p} | {c} | {100 * c / total_err:.1f}% |")

    lines += [
        "", f"**Demo-recipe subset** (true verb in `{args.recipe}`: "
        f"{', '.join(recipe_verbs)}): accuracy **{demo_acc:.4f}** over "
        f"{int(mask.sum())} segments. The recipe prior masks fires of "
        "non-recipe verbs at runtime, so confusions the prior can route "
        "around (e.g. open<->close) hurt the demo far less than the raw "
        "numbers suggest; in-recipe recall is what a retrain must move.",
    ]

    lines += ["", "## 3. min_conf sweep — majority smoother (demo knob)", "",
              "Same replay protocol as the bake-off: coverage = fraction of "
              "ticks with a confident verb; fires = stabilized verb edges.",
              "", "| config | coverage | tick acc | fires | fire precision |",
              "|---|---|---|---|---|"]
    for r in sweep:
        lines.append(f"| {r['smoother']} | {r['coverage']} | {r['tick_acc']} "
                     f"| {r['fires']} | {r['fire_precision']} |")

    out = Path(args.out)
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()

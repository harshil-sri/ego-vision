"""HoloAssist: does the avoidance of fine-motor work depend on how long the action lasts?

The avoidance of fine-motor seconds by routine instructor speech
(scripts.holoassist_timing) was not found in cooking (WTaG,
scripts.wtag_label_check). One possible reason: screw, unscrew and insert
hold hands and eyes on one small part for several seconds, and kitchen
actions do not. If so, on HoloAssist itself the avoidance should be
weaker for short fine-motor actions, and long actions of OTHER verbs
should also be avoided.

Labels only. Every second of a video belongs to one labelled action or
to idle time. Each action is put in a class:

    group   fine (screw, unscrew, insert) / other verb
    length  under 2 s, 2 to 5 s, 5 to 10 s, 10 s and more

Routine speech = instructor-started utterances that are not corrections.
For each class: onsets that fall inside such actions, observed /
expected; expected = mean over circular shifts of the onsets inside each
video (as in scripts.holoassist_timing).

Usage:  python -m scripts.holoassist_action_length
Outputs: reports/holoassist_action_length.json, reports/holoassist_action_length.md
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path

import numpy as np

from scripts.holoassist_timing import LABELS, build_video
from src.paths import resolve_data_path

FINE = {"screw", "unscrew", "insert"}
BINS = [0.0, 2.0, 5.0, 10.0, np.inf]
BIN_NAMES = ["under 2 s", "2 to 5 s", "5 to 10 s", "10 s and more"]
GROUPS = ["fine", "other verb"]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--shifts", type=int, default=1000)
    args = ap.parse_args()
    rng = np.random.default_rng(0)
    data = json.loads(Path(resolve_data_path(LABELS)).read_text(encoding="utf-8"))
    counts = Counter(e["attributes"].get("Verb") for v in data for e in v["events"]
                     if e["label"] == "Fine grained action")
    top = [v for v, _ in counts.most_common(20)]
    fine_ids = {i for i, n in enumerate(top) if n in FINE}
    IDLE = len(top) + 1
    C = len(GROUPS) * len(BIN_NAMES) + 1                     # last class = idle
    obs = {k: np.zeros(C) for k in ("routine", "correction")}
    null = {k: np.zeros((args.shifts, C)) for k in obs}
    seconds = np.zeros(C)
    n_videos = 0
    for v in data:
        V = build_video(v, top)
        if V is None:
            continue
        n_videos += 1
        st, dur = V["state"], V["a_end"] - V["a_start"]                  # per piece; nan when idle
        cls = np.full(len(st), C - 1)
        act = st != IDLE
        g = np.where(np.isin(st, list(fine_ids)), 0, 1)
        b = np.clip(np.searchsorted(BINS, np.nan_to_num(dur, nan=0.0), side="right") - 1, 0, len(BIN_NAMES) - 1)
        cls[act] = (g * len(BIN_NAMES) + b)[act]
        seconds += np.bincount(cls, weights=np.diff(V["edges"]), minlength=C)
        W = V["hi"] - V["lo"]
        corr = V["onsets"]["correct"]
        allp = V["onsets"]["all_instructor"]
        ev = {"routine": allp[~np.isin(allp, corr)], "correction": corr}
        for k, t in ev.items():
            if len(t) == 0:
                continue
            off = np.concatenate([[0.0], rng.uniform(0, W, args.shifts)])
            tt = V["lo"] + np.mod(t[None, :] - V["lo"] + off[:, None], W)
            kk = np.clip(np.searchsorted(V["edges"], tt, side="right") - 1, 0, len(st) - 1)
            c = cls[kk]
            for j in range(C):
                n = (c == j).sum(1)
                obs[k][j] += n[0]
                null[k][:, j] += n[1:]

    names = [f"{g}, {b}" for g in GROUPS for b in BIN_NAMES] + ["idle"]
    res = {"videos": n_videos, "shifts": args.shifts,
           "onsets": {k: int(o.sum()) for k, o in obs.items()}, "classes": {}}
    for j, n in enumerate(names):
        row = {"hours": round(float(seconds[j] / 3600), 1), "share_of_time": round(float(seconds[j] / seconds.sum()), 3)}
        for k in obs:
            e = max(null[k][:, j].mean(), 1e-9)
            row[k] = {"n": int(obs[k][j]), "ratio": round(float(obs[k][j] / e), 2),
                      "chance95": [round(float(np.percentile(null[k][:, j], 2.5) / e), 2),
                                   round(float(np.percentile(null[k][:, j], 97.5) / e), 2)]}
        res["classes"][n] = row
    Path("reports/holoassist_action_length.json").write_text(json.dumps(res, indent=2))

    L = ["# HoloAssist: avoidance of an action by its length", "",
         f"Generated by `python -m scripts.holoassist_action_length`. {n_videos} videos, labels only, "
         f"{res['onsets']['routine']} routine instructor onsets, {res['onsets']['correction']} corrections. "
         "fine = screw, unscrew, insert. See the script docstring.", "",
         f"Each cell: onsets inside such actions, observed / expected [range of 95% of {args.shifts} shifts], n.", "",
         "| action | hours | share of time | routine speech | corrections |", "|---|---|---|---|---|"]
    for n, r in res["classes"].items():
        cell = lambda d: f"{d['ratio']:.2f} [{d['chance95'][0]:.2f}, {d['chance95'][1]:.2f}], n {d['n']}"
        L.append(f"| {n} | {r['hours']} | {r['share_of_time']:.1%} | {cell(r['routine'])} | {cell(r['correction'])} |")
    Path("reports/holoassist_action_length.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))


if __name__ == "__main__":
    main()
